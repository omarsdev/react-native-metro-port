#!/bin/bash
#
# Build phase: decides which Metro port this build should use and writes it to a
# generated header that ios/RNMetroPort.m compiles in.
#
# Order of preference:
#   1. RCT_METRO_PORT, which `react-native run-ios` passes to xcodebuild.
#   2. The Metro that reports this project as its root. A plain Xcode build has no
#      RCT_METRO_PORT, and "something answers on 8081" isn't enough: that may be
#      another project's Metro.
#
# A convenience must never fail the build, so this always exits 0 and there is no
# `set -e`.

set -u

readonly DEFAULT_PORT=8081
readonly SCAN_START="${RN_METRO_PORT_SCAN_START:-$DEFAULT_PORT}"
readonly SCAN_COUNT="${RN_METRO_PORT_SCAN_COUNT:-10}"
readonly CONFIG_HEADER="${DERIVED_FILE_DIR}/RNMetroPortConfig.h"

log() {
  echo "note: react-native-metro-port: $*"
}

# Metro sends this as a URL pathname, so "/my app" arrives as "/my%20app", and some
# CLI versions build it from "file:///" + cwd, which leaves a doubled leading slash.
metro_project_root() {
  local value
  value="$(curl --silent --max-time 1 --dump-header - --output /dev/null \
    "http://localhost:$1/status" \
    | tr -d '\r' \
    | grep -i '^x-react-native-project-root:' \
    | cut -d' ' -f2-)"
  value="$(printf '%b' "${value//%/\\x}")"
  echo "/${value#"${value%%[!/]*}"}"
}

find_project_port() {
  local project_root port
  project_root="$(cd "${PODS_ROOT}/../.." && pwd -P)"

  for ((port = SCAN_START; port < SCAN_START + SCAN_COUNT; port++)); do
    if [[ "$(metro_project_root "$port")" == "$project_root" ]]; then
      echo "$port"
      return
    fi
  done
}

resolve_port() {
  if [[ -z "${RCT_METRO_PORT:-}" ]]; then
    find_project_port
  elif [[ "$RCT_METRO_PORT" =~ ^[0-9]+$ ]]; then
    echo "$RCT_METRO_PORT"
  else
    echo "warning: react-native-metro-port: ignoring invalid RCT_METRO_PORT '$RCT_METRO_PORT'" >&2
    find_project_port
  fi
}

port="$(resolve_port)"

config="// Generated by react-native-metro-port. Do not edit."
if [[ -n "$port" && "$port" != "$DEFAULT_PORT" ]]; then
  config+=$'\n'"#define RN_METRO_PORT_RESOLVED $port"
  log "this build will use Metro on port $port"
else
  log "no custom port, leaving React Native's default in place"
fi

mkdir -p "$(dirname "$CONFIG_HEADER")"
if [[ ! -f "$CONFIG_HEADER" ]] || [[ "$(cat "$CONFIG_HEADER")" != "$config" ]]; then
  printf '%s\n' "$config" > "$CONFIG_HEADER"
fi

exit 0
