#!/bin/bash
#
# Decides which Metro port a debug build should use, then records it for the app.
# Runs as an Xcode build phase on iOS and as a Gradle task on Android.
#
# Order of preference:
#   1. The port the build was given, if the Metro there is this project's. That's
#      RCT_METRO_PORT from `react-native run-ios` or reactNativeDevServerPort from
#      `react-native run-android`. It can be wrong: before CLI 20.2 both commands
#      kept the old port after you accepted the "use another port?" prompt.
#   2. The Metro that reports this project as its root. A plain Xcode or Android
#      Studio build is given no port, and "something answers on 8081" isn't enough:
#      that may be another project's Metro.
#   3. The port the build was given, if nothing better turned up. Metro may not have
#      started yet, or it may be too old to report its root (before React Native
#      0.73), and then there's nothing to check it against.
#
# A convenience must never fail the build, so this always exits 0 and there is no
# `set -e`.

set -u

readonly DEFAULT_PORT="${RN_METRO_PORT_DEFAULT:-8081}"
readonly SCAN_START="${RN_METRO_PORT_SCAN_START:-$DEFAULT_PORT}"
readonly SCAN_COUNT="${RN_METRO_PORT_SCAN_COUNT:-10}"

log() {
  echo "note: react-native-metro-port: $*"
}

warn() {
  echo "warning: react-native-metro-port: $*" >&2
}

# Prints the project a Metro reports, "unknown" for a server that doesn't report one,
# and nothing when no server answers.
#
# Metro sends the root as a URL pathname, so "/my app" arrives as "/my%20app", and
# some CLI versions build it from "file:///" + cwd, which leaves a doubled leading
# slash.
metro_project_root() {
  local headers value
  headers="$(curl --silent --max-time 1 --dump-header - --output /dev/null \
    "http://localhost:$1/status")" || return 0
  [[ -n "$headers" ]] || return 0

  value="$(printf '%s\n' "$headers" \
    | tr -d '\r' \
    | grep -i '^x-react-native-project-root:' \
    | cut -d' ' -f2-)"
  if [[ -z "$value" ]]; then
    echo unknown
    return 0
  fi
  value="$(printf '%b' "${value//%/\\x}")"
  echo "/${value#"${value%%[!/]*}"}"
}

find_project_port() {
  local port
  for ((port = SCAN_START; port < SCAN_START + SCAN_COUNT; port++)); do
    if [[ "$(metro_project_root "$port")" == "$project_root" ]]; then
      echo "$port"
      return
    fi
  done
}

resolve_port() {
  local given_root found
  if [[ -z "$given_port" ]]; then
    find_project_port
    return
  fi

  given_root="$(metro_project_root "$given_port")"
  if [[ "$given_root" == "$project_root" || "$given_root" == unknown ]]; then
    echo "$given_port"
    return
  fi

  found="$(find_project_port)"
  if [[ -n "$found" ]]; then
    echo "$found"
    return
  fi
  if [[ -n "$given_root" ]]; then
    warn "port $given_port belongs to another project ($given_root) and this project's Metro wasn't found"
  fi
  echo "$given_port"
}

write_if_changed() {
  mkdir -p "$(dirname "$1")"
  if [[ ! -f "$1" ]] || [[ "$(cat "$1")" != "$2" ]]; then
    printf '%s\n' "$2" > "$1"
  fi
}

write_ios_header() {
  local config="// Generated by react-native-metro-port. Do not edit."
  if [[ -n "$override" ]]; then
    config+=$'\n'"#define RN_METRO_PORT_RESOLVED $override"
  fi
  write_if_changed "${DERIVED_FILE_DIR}/RNMetroPortConfig.h" "$config"
}

write_android_resource() {
  write_if_changed "$RN_METRO_PORT_ANDROID_RES" "<?xml version=\"1.0\" encoding=\"utf-8\"?>
<resources>
  <integer name=\"rn_metro_port\">${override:-0}</integer>
</resources>"
}

# The app on a USB device reaches the Mac through `adb reverse`, which only the CLI
# sets up. An emulator doesn't need it, but telling them apart isn't worth the code.
reverse_android_port() {
  local serial
  "$ADB" devices 2>/dev/null | awk 'NR > 1 && $2 == "device" { print $1 }' \
    | while read -r serial; do
      "$ADB" -s "$serial" reverse "tcp:$1" "tcp:$1" > /dev/null 2>&1
    done
}

# CocoaPods builds a Debug-only pod in every configuration and just doesn't link it,
# so this phase runs in Release too. Without DEBUG, ios/RNMetroPort.m compiles to
# nothing, so there's no port to look for.
if [[ -z "${RN_METRO_PORT_ANDROID_RES:-}" && " ${GCC_PREPROCESSOR_DEFINITIONS:-} " != *" DEBUG=1 "* ]]; then
  override=""
  write_ios_header
  exit 0
fi

if [[ -n "${PROJECT_ROOT:-}" ]]; then
  project_root="$(cd "$PROJECT_ROOT" && pwd -P)"
else
  project_root="$(cd "${PODS_ROOT}/../.." && pwd -P)"
fi

given_port="${RCT_METRO_PORT:-}"
if [[ -n "$given_port" && ! "$given_port" =~ ^[0-9]+$ ]]; then
  warn "ignoring invalid RCT_METRO_PORT '$given_port'"
  given_port=""
fi

port="$(resolve_port)"

# A port of 8081 still has to be set if the build was given a different one, or the
# app would use the port that was just rejected.
override=""
if [[ -n "$port" && ("$port" != "$DEFAULT_PORT" || "${given_port:-$DEFAULT_PORT}" != "$DEFAULT_PORT") ]]; then
  override="$port"
fi

if [[ -n "$override" ]]; then
  log "this build will use Metro on port $override"
else
  log "no custom port, leaving React Native's default in place"
fi

if [[ -n "${RN_METRO_PORT_ANDROID_RES:-}" ]]; then
  write_android_resource
  if [[ -n "$port" && -n "${ADB:-}" ]]; then
    reverse_android_port "$port"
  fi
else
  write_ios_header
fi

exit 0
